def render_evals(spec: Spec, num: int, version: str) -> str:
    cs = cases(spec.block(12))
    lines = [f"# Приёмочные кейсы — Агент № {num}, {spec.fm('имя агента')}", "",
             f"Версия агента {version}. Прогон ручной, вердикт машинный: ответы целиком — в "
             "`прогон_<ГГГГ-ММ-ДД>.md` рядом; вердикт по форме — `check_run.py`; вердикт по существу — "
             "приёмщик по ожиданию из спецификации (`evals_and_acceptance.md`).", ""]
    n_cl = len(checklist_items(spec.block(8)))
    for i, c in enumerate(cs, 1):
        blocking = c["id"] in REQUIRED_CASES or c["id"] == "same_input_twice"
        pref = "Б" if blocking else "О"
        feats = list(c["features"]) or list(DEFAULT_FEATURES.get(c["id"], []))
        if not feats:
            feats = [("есть-любое", "результат | источники | ограничения")]
            if n_cl and c["id"] not in ("external_action_without_confirmation", "missing_required_input"):
                feats.insert(0, ("строк-таблицы>=", str(n_cl)))
        lines += [f"### {pref}-{num}.{i} · {c['id']}", "",
                  f"**Подать:** {c['input'] or 'см. спецификацию, блок 12'}", "",
                  f"**Ожидается:** {c['expect'] or 'поведение по навыку'}", "",
                  "**Признаки:**"]
        lines += [f"- {k}: {v}" for k, v in feats]
        lines += ["", f"**Провал означает:** {'версия не внедрена или поведение откатилось — комплект не передаётся' if blocking else 'находка в бэклог агента; передачу не останавливает'}", ""]
    return "\n".join(lines)


def render_run_file(spec: Spec, num: int, version: str, today: str, responses: Path | None) -> str | None:
    """Файл прогона из ответов агента (папка с файлами `<NN>_<id>.md`)."""
    if not responses or not Path(responses).is_dir():
        return None
    cs = cases(spec.block(12))
    by_id = {}
    for p in sorted(Path(responses).glob("*.md")):
        m = re.match(r"^\d+_([a-z0-9_]+)\.md$", p.name)
        if m:
            by_id.setdefault(m.group(1), p)
    lines = [f"# Прогон агента № {num} — {today}", "",
             f"**Условия:** версия агента {version} · модель класса Sonnet (стенд фабрики, не платформа) · "
             "аккаунт исполнителя · коннекторов нет", ""]
    n = 0
    for i, c in enumerate(cs, 1):
        p = by_id.get(c["id"]) or by_id.get({"same_input_twice": "happy_path_repeat"}.get(c["id"], ""))
        if not p:
            continue
        pref = "Б" if (c["id"] in REQUIRED_CASES or c["id"] == "same_input_twice") else "О"
        lines += [f"### {pref}-{num}.{i}", "", p.read_text(encoding="utf-8").strip(), ""]
        n += 1
    return "\n".join(lines) if n else None


