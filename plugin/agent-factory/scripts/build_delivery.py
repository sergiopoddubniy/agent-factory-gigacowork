def render_journal(spec: Spec, version: str, today: str, note: str, previous: str | None) -> str:
    prev_v = "—"
    if previous:
        m = re.search(r"\*\*Версия:\*\*\s*(V\d+)", previous)
        prev_v = m.group(1) if m else "—"
    entry = [f"## {version} · {today}", "",
             f"**Версия:** {version}", f"**Дата:** {today}", f"**Предыдущая версия:** {prev_v}",
             f"**Основание:** спецификация {spec.slug} · {spec.fm('версия спецификации')} · отпечаток {spec.fp}", "",
             f"**Что изменилось:** {note}",
             "**Почему:** правка спецификации (пакет порождён из неё, руками не правился).",
             "**Чем закрыто:** пересборка, аудит пакета и сверка состава поставки — см. `СБОРКА.md`.", "",
             "**Что перенести в пространство:** перезалить навык из `00_Навык_" + spec.slug + ".md`, "
             "обновить карточку по `01_Карточка_агента_" + spec.slug + ".md` и команды по "
             "`02_Команды_" + spec.slug + ".md`; первый запуск — в контуре по фронтматтеру навыка.", ""]
    head = [f"# Журнал изменений агента — {spec.fm('имя агента')}", "",
            "Что изменилось / почему / чем закрыто — по каждой версии; текущая версия сверху.", ""]
    if previous:
        body = previous.split("\n## ", 1)
        old = ("## " + body[1]) if len(body) > 1 else ""
        return "\n".join(head + entry) + "\n" + old
    return "\n".join(head + entry)


