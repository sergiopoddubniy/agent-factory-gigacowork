def _d(s: str) -> str:
    """Дата в имя папки: 2026-09-21 → 21.09.26."""
    y, m, d = s.split("-")
    return f"{d}.{m}.{y[2:]}"


def _md_list(items, empty="—") -> str:
    return "\n".join(f"- {x}" for x in items) if items else f"- {empty}"


def _copy_dir_files(src: Path | None, dst: Path) -> list:
    """Копирует файлы (не папки-архивы) из src в dst; возвращает имена."""
    names = []
    if not src:
        return names
    src = Path(src)
    if not src.is_dir():
        print(f"ОШИБКА ВХОДА: папка не найдена: {src}", file=sys.stderr)
        sys.exit(EXIT_INPUT)
    for p in sorted(src.rglob("*")):
        if p.is_file() and not p.name.startswith(".") and p.suffix.lower() != ".zip":
            rel = p.relative_to(src)
            (dst / rel).parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(p, dst / rel)
            names.append(rel.as_posix())
    return names


