def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Комплект поставки из спецификации")
    ap.add_argument("--spec", required=True)
    ap.add_argument("--out", required=True, help="корень поставки (создаётся; агентная папка пересобирается)")
    ap.add_argument("--задача", dest="task", choices=TASKS, default="демонстрация")
    ap.add_argument("--поколение", dest="gen", choices=["2", "1.5"], default="2")
    ap.add_argument("--номер", dest="num", type=int, default=1, help="номер агента в пространстве")
    ap.add_argument("--version", default="V1", help="версия агента, V<N>")
    ap.add_argument("--date", default=date.today().isoformat())
    ap.add_argument("--client", default="Клиент")
    ap.add_argument("--kb", default=None, help="папка с файлами базы знаний пространства")
    ap.add_argument("--synthetic", default=None, help="папка с синтетикой для показа")
    ap.add_argument("--calibration", default=None, help="папка с реальными обезличенными документами (не на демонстрацию)")
    ap.add_argument("--responses", default=None, help="папка с ответами агента <NN>_<id>.md (П13, запасной результат)")
    ap.add_argument("--acceptance", default=None, help="файл приёмочного прогона для пакета доказательств")
    ap.add_argument("--note", default="первая сборка из спецификации", help="что изменилось (журнал)")
    ap.add_argument("--no-check", action="store_true", help="не запускать проверки после сборки")
    ap.add_argument("--расчётная", "--расчетная", dest="calc", action="store_true",
                    help="расчётная задача: в базе знаний обязан быть пустой шаблон .xlsx (Я10); "
                         "равносильно `расчётная: да` во фронтматтере спецификации")
    args = ap.parse_args(argv)

    spec = parse_spec(Path(args.spec))
    if spec.problems:
        print("СПЕЦИФИКАЦИЯ НЕ РАЗОБРАНА:\n  - " + "\n  - ".join(spec.problems))
        return EXIT_INPUT
    gate = readiness_check(spec, "demo")
    if gate["verdict"] != "PASS":
        print(render_readiness(gate))
        print("\nСБОРКА ОСТАНОВЛЕНА: спецификация ниже порога demo — комплект не порождается.")
        return EXIT_RED
    if not re.fullmatch(r"V\d+", args.version):
        print("ОШИБКА ВХОДА: --version вида V<N>", file=sys.stderr)
        return EXIT_INPUT

    root, num, slug, today = Path(args.out).resolve(), args.num, spec.slug, args.date
    name = spec.fm("имя агента")
    calc = bool(args.calc) or (spec.fm("расчётная") or spec.fm("расчетная") or "").strip().lower() in ("да", "yes", "true")
    root.mkdir(parents=True, exist_ok=True)
    slug_dir = f"{num}_{slug}_{args.version}_{_d(today)}"
    kb_dir, synth_dir = f"{num}_{slug}", f"{num}_{slug}"
    ws, conns = workspace_skills(spec.block(11)), connectors(spec.block(11))
    cmds = all_commands(spec, num)

    # --- папка агента (пересобирается целиком; прежние версии папки убираются) ---
    pkgs = root / "04_Пакеты_агентов"
    pkgs.mkdir(exist_ok=True)
    previous_journal = None
    for old in pkgs.glob(f"{num}_{slug}_V*"):
        j = old / f"04_ЖУРНАЛ_ИЗМЕНЕНИЙ_{slug}.md"
        if j.exists():
            previous_journal = j.read_text(encoding="utf-8")
        shutil.rmtree(old)
    agent = pkgs / slug_dir
    agent.mkdir()
    skill_text = render_skill(spec, args.version, today, num)
    if ws:
        # Раздел 0 — обязательная активация навыков пространства (agent_package.md)
        steps = "\n".join(f"{i}. Навык пространства «{w['name']}» — {w['why'] or 'правила вызовов внешней системы'}."
                          for i, w in enumerate(ws, 1))
        sec0 = (f"## 0. Обязательная активация навыков\n\n**До любого действия активируй по порядку:**\n\n"
                f"{steps}\n{len(ws) + 1}. Свой навык «{name}».\n\n"
                "Всегда, а не тогда, когда решишь, что данные понадобятся. Навыка нет в пространстве — "
                "скажи первой строкой ответа и **не восстанавливай порядок работы по памяти**: неверный "
                "вызов возвращает правдоподобный ответ.\n\n")
        skill_text = skill_text.replace("\n## 1. Назначение", "\n" + sec0 + "## 1. Назначение", 1)
    command_text = render_command(spec, args.version, today)
    (agent / f"00_Навык_{slug}.md").write_text(skill_text, encoding="utf-8")
    (agent / f"01_Карточка_агента_{slug}.md").write_text(render_card(spec, num, args.version, today, args.task), encoding="utf-8")
    (agent / f"02_Команды_{slug}.md").write_text(render_commands(spec, num, args.version, today), encoding="utf-8")
    (agent / f"04_ЖУРНАЛ_ИЗМЕНЕНИЙ_{slug}.md").write_text(
        render_journal(spec, args.version, today, args.note, previous_journal), encoding="utf-8")

    # --- база знаний ---
    kb = root / "01_База_знаний_workspace" / kb_dir
    if kb.exists():
        shutil.rmtree(kb)
    kb.mkdir(parents=True)
    kb_copied = _copy_dir_files(args.kb, kb)
    (kb / "проверка").mkdir(exist_ok=True)
    (kb / "проверка" / f"evals_{slug}.md").write_text(render_evals(spec, num, args.version), encoding="utf-8")
    run_text = render_run_file(spec, num, args.version, today, args.responses)
    if run_text:
        (kb / "проверка" / f"прогон_{today}.md").write_text(run_text, encoding="utf-8")
    kb_extra = {"проверка": "приёмочные кейсы с машинными признаками и файлы прогонов (П12, П13); "
                            "агент их не читает как знание — это проверка"}
    (kb / "00_ЧТО_ЗДЕСЬ_И_ЧЕГО_ЗДЕСЬ_НЕТ.md").write_text(
        render_kb_map(spec, kb_copied, kb_files(spec.block(6)), kb_extra), encoding="utf-8")
    # Комплект без базы знаний — заготовка, не агент (SKILL.md исходного скилла,
    # «База знаний — часть управляющей логики»). Объявленный в спецификации файл,
    # которого нет в поставке, — жёсткий провал сборки, а не строка в карте.
    declared_kb = {d["file"] for d in kb_files(spec.block(6))}
    kb_missing = sorted(declared_kb - {Path(n).name for n in kb_copied})

    # --- синтетика / калибровка ---
    synth_names = []
    synth = root / "03_Синтетика_для_демо" / synth_dir
    if args.synthetic or args.task != "пилот":
        if synth.exists():
            shutil.rmtree(synth)
        synth.mkdir(parents=True)
        synth_names = _copy_dir_files(args.synthetic, synth)
        (synth / "README.md").write_text(render_synth_readme(spec, synth_names, num), encoding="utf-8")
    if args.calibration:
        cal = root / "Калибровочные_данные" / f"{num}_{slug}"
        if cal.exists():
            shutil.rmtree(cal)
        cal.mkdir(parents=True)
        names = _copy_dir_files(args.calibration, cal)
        (cal / "README_калибровка.md").write_text("\n".join([
            "# Калибровочные данные", "", "**Происхождение:** обезличено", "**Режим:** фикстура", "",
            "Реальные документы клиента для проверки качества, не для показа: что сверяется, как выглядит "
            "независимый разбор для сравнения, какие пункты блокирующие вне шкалы.", ""]
            + [f"- `{n}`" for n in names]), encoding="utf-8")

    # --- discovery: спецификация, ворота, план, доказательства ---
    disc = root / "02_Discovery_спецификация"
    disc.mkdir(exist_ok=True)
    shutil.copyfile(spec.path, disc / "AGENT_SPEC.md")
    gate_p = readiness_check(spec, "pilot")
    (disc / "ВОРОТА.md").write_text("# Ворота достаточности\n\n```text\n" + render_readiness(gate)
                                    + "\n\n" + render_readiness(gate_p) + "\n```\n", encoding="utf-8")
    if gate_p["verdict"] != "PASS":
        (disc / "ПЛАН_ДОБОРА.md").write_text(render_plan(build_plan(spec, "pilot"), spec), encoding="utf-8")

    # --- docx ---
    build_docx(spec, agent / f"03_Спецификация_{slug}.docx", args.client, num, args.version, today,
               cmds, kb_copied, synth_names, args.task)

    # --- надстройки ---
    extras = []
    if args.task == "демонстрация":
        extras += build_demo_extras(spec, root, num, synth_dir if synth_names or synth.exists() else None,
                                    Path(args.responses) if args.responses else None)
    elif args.task == "воркшоп":
        extras += build_workshop_extras(spec, root, num)
    else:
        extras += build_pilot_extras(spec, root, num, slug_dir, today)

    # --- файлы уровня комплекта ---
    (root / "00_Карта_джоб.md").write_text(render_job_map(spec, num, slug_dir), encoding="utf-8")
    (root / "00_ПЕРЕИСПОЛЬЗОВАНИЕ.md").write_text(render_reuse(spec), encoding="utf-8")
    (root / "00_Инструкция_по_сборке_пространства.md").write_text(
        render_assembly(spec, num, slug_dir, kb_dir, args.gen, ws, conns, cmds, args.task, calc), encoding="utf-8")
    (root / "00_Как_использовать_этот_комплект.md").write_text(
        render_entry_point(spec, num, slug_dir, kb_dir, synth_dir if synth_names or synth.exists() else None,
                           args.task, cmds, extras), encoding="utf-8")

    # --- пакет для загрузки (вне поставки) + аудит пакета ---
    upload = root.parent / f"{root.name}_загрузка"
    pkg = upload / slug
    if pkg.exists():
        shutil.rmtree(pkg)
    (pkg / "commands").mkdir(parents=True)
    (pkg / "skills" / "00-agent-skill").mkdir(parents=True)
    (pkg / "skills" / "00-agent-skill" / "SKILL.md").write_text(skill_text, encoding="utf-8")
    (pkg / "commands" / "run-agent.md").write_text(command_text, encoding="utf-8")
    from check_package import audit_package, render as render_audit  # noqa: E402
    audit = audit_package(pkg, spec.path)
    sha = ""
    zip_path = upload / f"{slug}.zip"
    if zip_path.exists():
        zip_path.unlink()
    if audit["status"] == "PASS":
        write_zip(zip_path, pkg)
        sha = hashlib.sha256(zip_path.read_bytes()).hexdigest()

    # --- пакет доказательств (контракт завершения) ---
    ev_line = "не собран (нет файла прогона: --acceptance)"
    if args.acceptance:
        from evidence_bundle import build_bundle, render as render_bundle  # noqa: E402
        acc = Path(args.acceptance)
        if not acc.is_file():
            print(f"ОШИБКА ВХОДА: файл прогона не найден: {acc}", file=sys.stderr)
            return EXIT_INPUT
        threshold = "pilot" if args.task == "пилот" else "demo"
        bundle = build_bundle(spec.path, pkg, acc, threshold)
        (disc / "EVIDENCE_BUNDLE.md").write_text(render_bundle(bundle), encoding="utf-8")
        (disc / "EVIDENCE_BUNDLE.json").write_text(json.dumps(bundle, ensure_ascii=False, indent=2),
                                                   encoding="utf-8")
        shutil.copyfile(acc, disc / "ПРИЁМОЧНЫЙ_ПРОГОН.md")
        ev_line = f"{bundle['verdict']} (порог {threshold})"

    # --- сверка состава (оригинальный check_delivery.py) ---
    dc_line, dc_rc, dc_out = "не запускалась (--no-check)", None, ""
    if not args.no_check:
        r = subprocess.run([sys.executable, str(SCRIPTS / "check_delivery.py"), "--папка", str(root),
                            "--задача", args.task, "--поколение", args.gen] + (["--расчётная"] if calc else []),
                           capture_output=True, text=True)
        dc_rc, dc_out = r.returncode, r.stdout + r.stderr
        m = re.search(r"delivery composition check: (PASS|FAIL) \(([^)]*)\)", dc_out)
        dc_line = f"{m.group(1)} ({m.group(2)})" if m else ("PASS" if dc_rc == 0 else "FAIL")
        fails = [ln.strip() for ln in dc_out.splitlines() if ln.strip().startswith("[FAIL]")]
    else:
        fails = []

    if kb_missing:
        fails.insert(0, "[FAIL] Ф-БЗ  файлы базы знаний объявлены в спецификации (блок 6, «База знаний:»), но не переданы: "
                     + ", ".join(kb_missing) + " — передайте папку через --kb; комплект без базы знаний — заготовка")
    log = [f"# Сборка комплекта — {name}", "",
           f"- Дата: {today}", f"- Версия агента: {args.version} · номер {num} · задача: {args.task} · поколение {args.gen}"
           + (" · расчётная (Я10: пустой шаблон .xlsx в базе знаний)" if calc else ""),
           f"- Спецификация: {slug} · {spec.fm('версия спецификации')} · отпечаток {spec.fp}",
           f"- Ворота demo: {gate['verdict']} · pilot: {gate_p['verdict']}",
           f"- delivery composition check: {dc_line}",
           f"- structural audit: {audit['status']}",
           f"- evidence bundle: {ev_line}",
           "- platform runtime validation: требуется выполнить в конструкторе",
           "- deployed state check: требуется выполнить от лица не-администраторского аккаунта",
           f"- Архив для загрузки: {zip_path.name if sha else 'не создан (аудит FAIL)'}"
           + (f" · SHA-256 {sha} · папка `{upload.name}/` вне поставки" if sha else ""), ""]
    warns = [x for x in extras if x.startswith("[WARN]")]
    if warns:
        log += ["Предупреждения сборки (комплект собран, но до показа закрыть):", ""] + [f"- {w}" for w in warns] + [""]
    if fails:
        log += ["Строки FAIL сверки состава (комплект не передаётся, пока не закрыты):", ""]
        log += [f"- {f}" for f in fails]
    if audit["findings"]:
        log += ["", "Находки аудита пакета:", ""] + [f"- {f}" for f in audit["findings"]]
    (root / "СБОРКА.md").write_text("\n".join(log) + "\n", encoding="utf-8")
    (upload / "СБОРКА.json").write_text(json.dumps({"spec": slug, "fingerprint": spec.fp, "version": args.version,
                                                    "sha256": sha, "audit": audit["status"],
                                                    "delivery": dc_line}, ensure_ascii=False, indent=2),
                                        encoding="utf-8")

    print(render_audit(audit))
    if dc_out:
        print(dc_out.rstrip())
    print(f"\nкомплект: {root} · агент: {slug_dir} · архив: {'да · ' + sha[:12] if sha else 'нет'}")
    for f in fails:
        if f.startswith("[FAIL] Ф-БЗ"):
            print(f)
    ok = audit["status"] == "PASS" and (dc_rc in (0, None)) and not kb_missing
    return EXIT_OK if ok else EXIT_RED


if __name__ == "__main__":
    sys.exit(main())
