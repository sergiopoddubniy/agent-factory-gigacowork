#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Нормализация текста для поиска — один источник на все скрипты.

**Почему отдельным модулем.** Грубый стеммер и токенизатор появились сначала в
реестре агентов, потом были скопированы в базу шаблонов. Две копии разошлись
бы при первой же правке — это ровно тот дефект, который в скилле записан
правилом «два описания одного и того же». Здесь они в одном месте, и обе
стороны берут их отсюда.

**Почему стеммер грубый и почему это не лень.** Поиск идёт по двум десяткам
записей, и полнота там важнее точности: лишний кандидат виден человеку сразу,
пропущенный — не виден никогда. Морфологический анализатор потребовал бы
внешней зависимости, а весь скилл держится на стандартной библиотеке.
"""
from __future__ import annotations

import re
import unicodedata

nfc = lambda s: unicodedata.normalize("NFC", str(s))
nameflat = lambda s: re.sub(r"[\s_\-]+", " ", nfc(s)).lower().replace("ё", "е")

ТОКЕН = re.compile(r"[a-zA-Zа-яА-ЯёЁ0-9][a-zA-Zа-яА-ЯёЁ0-9\-]{2,}")

# Порядок важен: длинные окончания отсекаются раньше коротких, иначе «ого»
# никогда не сработает — сначала снимется «о».
ОКОНЧАНИЯ = ("ого", "его", "ому", "ему", "ыми", "ими", "ями", "ами",
             "ая", "яя", "ое", "ее", "ые", "ие", "ов", "ев", "ам", "ям",
             "ах", "ях", "ой", "ей", "ый", "ий", "ую", "юю", "ья", "ье",
             "а", "я", "ы", "и", "о", "е", "у", "ю", "ь", "й")


def основа(w: str) -> str:
    """Грубая основа слова: отсекается одно известное окончание, затем «й».

    Второй проход по «й» — не украшение. «Казначей» даёт основу «казнач», а
    «казначея» — «казначе»: разные слова для поиска, и запрос ролью перестаёт
    находить агента с этой ролью. Именно этот случай и заставил вынести
    стеммер в общий модуль.
    """
    if len(w) < 6 or not re.match(r"^[а-я]", w):
        return w
    for о in ОКОНЧАНИЯ:
        if w.endswith(о) and len(w) - len(о) >= 4:
            w = w[:-len(о)]
            break
    # Второй проход. «Казначей» после первого прохода даёт «казнач» (снято
    # «ей»), а «казначея» — «казначе» (снято «я»). Для поиска это разные
    # слова, и запрос ролью перестаёт находить агента с этой ролью. Добивка
    # хвостовой гласной или «й» сводит обе формы к одной основе.
    if len(w) > 4 and w[-1] in "йеаоуыэюя":
        w = w[:-1]
    return w


def токены(s: str) -> list[str]:
    return [основа(m.group(0).lower().replace("ё", "е"))
            for m in ТОКЕН.finditer(nfc(s))]
