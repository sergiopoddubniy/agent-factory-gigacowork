#!/usr/bin/env python3
"""
context_quality.py — оценка качества операционного контекста агента ДО прогона.

Зачем отдельно от прогона. В валидации на 10 000 ходов проработка контекста
снижала долю дефектных ходов с 65,7% до 17,8%, тогда как переход от средней
модели к сильной не давал почти ничего (25,2% → 24,9%). Причём оценка одного
контекста предсказывала исход лучше, чем оценка поведения агента: AUC 0,88
против 0,80. То есть посмотреть на комплект до запуска информативнее, чем
посмотреть на его ответы после.

Что здесь считается контекстом. Всё, что задаёт рабочую среду агента:
`SKILL.md`, поле «Инструкция» карточки, файлы команд, справочные файлы базы
знаний, описания коннекторов. Не только промпт.

Семь осей взяты из работы про готовность агентов; проверки под каждой осью —
наши, по нашим артефактам.

ЧЕСТНАЯ ОГОВОРКА. Это не воспроизведение чужого индекса: их пороги
откалиброваны на исходах 10 000 ходов, наши — нет. Наш счёт показывает, где
контекст тоньше, и не предсказывает вероятность отказа. Пока не накоплены
прогоны, число здесь — карта того, что чинить, а не прогноз.

Запуск:
    python3 context_quality.py <папка_агента> [--json]
    python3 context_quality.py <папка_портфеля> --все
"""
from __future__ import annotations

import argparse
import json
import math
import pathlib
import re
import sys
import unicodedata
from pathlib import Path

nfc = lambda s: unicodedata.normalize("NFC", s)
flat = lambda s: re.sub(r"[\s]+", " ", nfc(s)).lower().replace("ё", "е")

# Порог поля «Инструкция» карточки. Взят из практики: длиннее — обрезается
# при вставке, и хвост теряется незаметно.
CARD_LIMIT = 12000


class Axis:
    def __init__(self, key: str, name: str, why: str):
        self.key, self.name, self.why = key, name, why
        self.checks: list[tuple[str, bool, str]] = []

    def add(self, name: str, ok: bool, detail: str = "") -> None:
        self.checks.append((name, bool(ok), detail))

    @property
    def score(self) -> float:
        if not self.checks:
            return 0.0
        return 100.0 * sum(1 for _, ok, _ in self.checks if ok) / len(self.checks)


def load(agent: Path) -> dict:
    """Собирает контекст агента из того, что физически лежит на диске."""
    out = {"skill": "", "card": "", "commands": "", "kb": {}, "files": []}
    for p in sorted(agent.rglob("*")):
        if not p.is_file() or p.name == ".DS_Store":
            continue
        out["files"].append(p.name)
        if p.suffix.lower() not in (".md", ".txt", ".yaml", ".yml"):
            continue
        try:
            t = p.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        n = flat(p.name)
        # Опознание артефактов — по тем же признакам, что в сверке комплекта.
        # Здесь были свои, более узкие: навык искался только как `SKILL.md`, а
        # карточка — как «01 агент…». В наших пакетах они давно называются
        # `00_Навык_<slug>.md` и `01_Карточка_агента_<slug>.md`, поэтому оба
        # артефакта падали в базу знаний. Следствие тихое и обманчивое: оси
        # искали слова «по всему тексту» и находили их, а ясность роли и
        # согласованность считались по пустой строке. Третий случай одного и
        # того же — измеритель со своим представлением об именах.
        имя_плоско = re.sub(r"[\s_\-]+", " ", n)
        if p.name == "SKILL.md" or имя_плоско.startswith("00 навык"):
            out["skill"] = t
        elif "карточк" in имя_плоско or re.match(r"^0[12] агент ", имя_плоско):
            out["card"] += t
        elif p.name == "run-agent.md" or "команд" in имя_плоско:
            # Канонический файл команды Поколения 2 называется латиницей и не
            # содержит слова «команда». Пока он не опознавался, он падал в
            # базу знаний, а ось согласованности — в ноль.
            out["commands"] += t
        else:
            out["kb"][p.name] = t
    return out


def find_card(agent: Path, cards_dir: Path | None) -> str:
    """Карточка агента часто лежит не рядом с навыком, а в общей папке описаний.

    Без этого проверка согласованности показывала 50 у всех семи агентов —
    и это был дефект измерителя, а не комплекта: карточка существовала, просто
    в соседнем каталоге.
    """
    if not cards_dir or not cards_dir.is_dir():
        return ""
    num = agent.name.split("_", 1)[0]
    slug = agent.name.split("_", 1)[1] if "_" in agent.name else agent.name
    for f in sorted(cards_dir.rglob("*.md")):
        n = flat(f.name)
        if slug.lower() in n or re.search(rf"агент[_ ]{num}\b", n):
            return f.read_text(encoding="utf-8", errors="replace")
    return ""


def assess(agent: Path, cards_dir: Path | None = None,
           kb_dir: Path | None = None) -> tuple[list[Axis], list[str]]:
    c = load(agent)
    if not c["card"]:
        c["card"] = find_card(agent, cards_dir)
    if kb_dir and kb_dir.is_dir():
        # Штатная структура портфеля: пакет — ZIP, база знаний — в
        # пространстве. Без этого ссылки на базу нечем проверить.
        extra = load(kb_dir)
        c["kb"].update(extra["kb"])
        c["files"] += extra["files"]
        if extra["skill"] and not c["skill"]:
            c["skill"] = extra["skill"]
    sk, card, cmds = flat(c["skill"]), flat(c["card"]), flat(c["commands"])
    kb_all = flat(" ".join(c["kb"].values()))
    whole = " ".join([sk, card, cmds, kb_all])
    blocks: list[str] = []
    A: list[Axis] = []

    # ── 1. Ясность роли ──────────────────────────────────────────────
    a = Axis("role", "Ясность роли",
             "агент, не знающий, кто он и для кого, подстраивается под запрос")
    a.add("названы пользователь и его должность", bool(re.search(r"пользовател|роль|должност|отдел", card or sk)))
    a.add("назван триггер — что запускает работу", "триггер" in whole or "запускает" in whole)
    a.add("есть раздел «чего агент не делает»",
          bool(re.search(r"не дела|out.of.scope|вне периметра|ты не ", whole)))
    a.add("роль одна, а не набор ролей",
          len(re.findall(r"ты — агент|ты - агент", card or sk)) <= 1,
          "две роли в одной карточке дают выбор между ними от запроса к запросу")
    A.append(a)

    # ── 2. Согласованность инструкций ────────────────────────────────
    a = Axis("consistency", "Согласованность инструкций",
             "два правила об одном предмете агент выбирает непредсказуемо")
    # У одиночного агента Поколения 2 карточки нет ПО КОНСТРУКЦИИ: агент — это
    # SKILL.md плюс commands/run-agent.md, весь текст живёт в навыке.
    # Ось, требовавшая карточку, ставила такому агенту ноль и через среднее
    # геометрическое роняла весь счёт — измеритель наказывал за следование
    # правилам скилла. Теперь ось для этого случая просто не применяется.
    gen2 = bool(cmds) and not card
    if gen2:
        a.checks = []           # ось неприменима и в среднее не входит
        a.add("Поколение 2: карточки нет по конструкции — ось не применяется", True)
        A.append(a)
    else:
        a.add("карточка есть отдельно от навыка", bool(card),
              "без карточки проверить согласованность не с чем")
    if card and sk:
        # Термины статусов и единиц должны совпадать между карточкой и навыком
        # Правило может стоять в карточке в повелительной форме («выноси
        # человеку»), а в навыке — в изъявительной. Это одно правило.
        TERMS = {"единица результата": ("единица результата", "единица "),
                 "строка сверки": ("строка сверки", "строкой сверки"),
                 "расхождение человеку": ("выносится человеку", "выноси человеку")}
        terms = [k for k, forms in TERMS.items() if any(f in sk for f in forms)]
        missing = [k for k in terms if not any(f in card for f in TERMS[k])]
        a.add("ключевые правила навыка отражены в карточке", not missing, f"нет в карточке: {missing}")
        # Прямое противоречие: одно и то же правило с разным содержанием
        contra = []
        for pat, why in [(r"сомнение[^.]{0,40}всегда[^.]{0,30}«?частично", "правило сомнения"),
                         (r"входные данные или папка", "источник входных данных")]:
            if re.search(pat, card) and not re.search(pat, sk):
                contra.append(why)
        a.add("в карточке нет правил, которых нет в навыке", not contra, str(contra))
        a.add("активация навыка прописана в карточке",
              "активируй навык" in card if card else False,
              "без этой фразы карточка не связана с логикой")
        A.append(a)

    # ── 3. Достаточность опоры ───────────────────────────────────────
    a = Axis("grounding", "Достаточность опоры",
             "агент без опоры рассуждает «вообще», а не по правилам компании")
    refs = set(re.findall(r"`([a-zA-Zа-яёА-ЯЁ_0-9\-]+\.md)`", nfc(c["skill"] + c["commands"])))
    have = {nfc(f) for f in c["files"]}
    # Ссылка на файл, которого нет на диске, — не всегда битая. Часть файлов
    # агент СОЗДАЁТ сам: отчёт, реестр решений, файл правил первого запуска.
    # Жёсткий список имён из одного прошлого проекта этого не покрывал и
    # объявлял дефектом штатное поведение.
    src = flat(c["skill"] + c["commands"])
    def is_output(ref: str) -> bool:
        # Имя файла в русском тексте склоняется: «работай с
        # `Правилами_консолидации.md`». Сравниваем по основе, иначе одно и то
        # же имя считается двумя разными файлами.
        r = re.sub(r"(ами|ой|ах|ам|ы|а|е|у|и)(_|\.)", r"\2", flat(ref))
        for m in re.finditer(re.escape(r), src):
            before = src[max(0, m.start() - 90): m.start()]
            around = src[max(0, m.start() - 120): m.end() + 120]
            # Ссылка, стоящая после «база знаний», «из», «по» — это файл,
            # который агент ЧИТАЕТ. Окно в 200 знаков захватывало соседние
            # предложения и объявляло выходом всё подряд: мутация с
            # удалённым файлом базы знаний переставала ловиться.
            if re.search(r"баз\w* знани|из файла|по файлу|читай|опира", before):
                continue
            if re.search(r"созда[её]т|сохрани|выдаёт|выдает|на выход|"
                         r"первым файлом|подготовь|результат перв", around):
                return True
        return False
    OUTPUT = {"01_решения_и_шаги.md", "02_матрица.md", "03_данные.md", "04_риски.md"}
    broken = [r for r in refs
              if nfc(r) not in have and r not in OUTPUT and r != "SKILL.md" and not is_output(r)]
    # У пакета Поколения 2 база знаний физически лежит в пространстве, а не
    # внутри пакета: ссылки на её файлы из пакета не резолвятся по построению.
    # Объявлять это битыми ссылками — значит наказывать за штатную поставку.
    kb_absent = gen2 and not c["kb"]
    if kb_absent:
        a.add("ссылки на базу знаний не проверены — оценивается только пакет", True,
              "передай папку базы знаний, чтобы проверить ссылки")
    else:
        a.add("все ссылки на файлы базы знаний резолвятся", not broken, str(broken[:3]))
        a.add("база знаний непустая", len(c["kb"]) > 0, f"файлов: {len(c['kb'])}")
    a.add("пороги и критерии вынесены в файлы, а не только в рассуждение",
          bool(re.search(r"критери|порог|методик|playbook|протокол", kb_all)))
    a.add("требование источника на каждое утверждение",
          bool(re.search(r"источник|со ссылк|url|цитат", whole)))
    A.append(a)

    # ── 4. Качество описания инструментов ────────────────────────────
    a = Axis("tools", "Описание инструментов",
             "слабо описанный инструмент вызывается неправильно или не вызывается")
    # Объявление «инструментов нет» проверяется ПЕРВЫМ.
    #
    # Прежде ветка выбиралась по слову «инструмент», а оно входит в саму фразу
    # «Подтверждённые инструменты: нет». Агент, честно объявивший отсутствие
    # коннекторов, попадал в ветку «инструменты есть» и получал красным «названы
    # конкретные вызовы» — то есть ось отключала собственную ветку. Подставить
    # туда фиктивное имя вызова значило бы вписать в навык вызов, которого агент
    # не делает.
    объявлено_без = bool(re.search(
        r"нет внешних коннектор|подтверждённые инструменты: нет|"
        r"инструментов нет|коннекторы не подтверждены|"
        r"коннекторов у этого агента нет|коннекторов нет|"
        r"работаешь только с загруженными", whole))
    # Признак наличия — слова, которых не бывает в отрицании: имя коннектора,
    # протокол, вызов. Голое слово «инструмент» признаком больше не считается.
    has_tools = (not объявлено_без) and bool(
        re.search(r"коннектор[а-я]*\s+[«\"'`]|mcp|\bapi\b|[a-z_]{4,}\(", whole))
    if has_tools:
        a.add("поведение при отказе инструмента задано",
              bool(re.search(r"повтори|retry|недоступ|деградац", whole)))
        a.add("границы записи заданы явно",
              bool(re.search(r"только чтени|не пишешь|write.back|external_write", whole)))
        a.add("названы конкретные вызовы, а не «инструмент вообще»",
              bool(re.search(r"[a-z_]{4,}\(|basis_|_balance|_card\b", whole)))
    else:
        # Агент без коннектора — не хуже агента с коннектором, если это
        # названо вслух. Раньше такая ось давала треть от возможного и
        # занижала комплект за честно объявленное ограничение.
        # Условие то же самое, что выбрало эту ветку. Раньше здесь стоял
        # собственный, более узкий список формулировок: ветка выбиралась одной
        # проверкой, а закрывалась другой, и агент, объявивший отсутствие
        # коннекторов словами «Коннекторов у этого агента нет», получал по этой
        # оси ноль. Два описания одного и того же в двадцати строках друг от
        # друга.
        a.add("инструментов нет по конструкции — и это сказано явно",
              объявлено_без,
              "если инструментов нет, это должно быть заявлено, а не подразумеваться")
    A.append(a)

    # ── 5. Покрытие ограничителей ────────────────────────────────────
    a = Axis("guardrails", "Покрытие ограничителей",
             "без них агент решает за человека там, где решать не должен")
    a.add("HITL-шлюз на внешние действия", "hitl" in whole)
    a.add("блокирующие quality gates", bool(re.search(r"quality gate|_check\b|blocking", whole)))
    a.add("расхождение выносится человеку", bool(re.search(r"выносится человеку|не выбирай сам|conflict_requires_review", whole)))
    a.add("единица результата задана источником", "единица результата" in whole)
    a.add("строка сверки", bool(re.search(r"строка сверки|обработано документов", whole)))
    a.add("правило неоднозначности задано заранее",
          bool(re.search(r"правило неоднозначн|сомнение|missing_data", whole)))
    A.append(a)

    # ── 6. Устойчивость к внедрению ──────────────────────────────────
    a = Axis("injection", "Устойчивость к внедрению",
             "инструкция внутри присланного документа выполняется молча")
    a.add("правило про инструкции внутри документов",
          bool(re.search(r"prompt.injection|инструкц\w+,? (спрятанн|внутри)|не выполняй инструкц", whole)))
    a.add("приёмочный кейс на внедрение",
          bool(re.search(r"prompt_injection|injection_in_document", whole)))
    a.add("правило про персональные данные и чувствительное",
          bool(re.search(r"персональн|чувствительн|не для распространения|конфиденциальн", whole)))
    A.append(a)

    # ── 7. Экономность ───────────────────────────────────────────────
    a = Axis("efficiency", "Экономность",
             "перегруженный контекст читается неравномерно: часть правил не срабатывает")
    card_len = len(c["card"])
    if gen2:
        # Третья по счёту ось, наказывавшая Поколение 2 за отсутствие того,
        # чего у него нет по конструкции. Поля «Инструкция» здесь не бывает,
        # и проверка длины срезала счёт каждому такому пакету на треть оси.
        a.add("Поколение 2: поля «Инструкция» нет — длина не проверяется", True)
    else:
        a.add(f"поле «Инструкция» в пределах {CARD_LIMIT} знаков",
              0 < card_len <= CARD_LIMIT if card else False, f"знаков: {card_len}")
    # Дубли абзацев — признак копипасты между файлами
    paras = [p.strip() for p in re.split(r"\n\s*\n", nfc(c["skill"])) if len(p.strip()) > 200]
    dup = len(paras) - len({flat(p) for p in paras})
    a.add("нет дублирующихся абзацев внутри навыка", dup == 0, f"дублей: {dup}")
    a.add("навык не разросся сверх читаемого",
          len(c["skill"]) < 60000, f"знаков в SKILL.md: {len(c['skill'])}")
    A.append(a)

    # ── Жёсткие блокировки: не усредняются ───────────────────────────
    # Осознанно повторяют логику «hard block»: критический дефект не должен
    # компенсироваться сильными сторонами.
    if not c["skill"]:
        blocks.append("нет SKILL.md — контекста как такового нет")
    if broken and not kb_absent:
        blocks.append(f"битые ссылки на базу знаний: {broken[:2]}")
    if "hitl" not in whole:
        blocks.append("нет ни одного HITL-шлюза")
    return A, blocks


def score_of(axes: list[Axis], blocks: list[str]) -> tuple[float, float]:
    """Возвращает (шкала, ворота).

    Шкала — среднее геометрическое по осям: слабая ось тянет вниз сильнее,
    чем при обычном среднем, и сильная сторона не компенсирует провал.
    Ворота — то же число, прижатое блокировкой.

    Различать обязательно. После блокировки ворота перестают двигаться, и
    только шкала показывает, улучшается ли комплект от версии к версии.
    """
    vals = [max(a.score, 1.0) for a in axes]
    gauge = math.exp(sum(math.log(v) for v in vals) / len(vals))
    gate = min(gauge, 49.0) if blocks else gauge
    return round(gauge, 1), round(gate, 1)


def band(gate: float, blocks: list[str]) -> str:
    if blocks:
        return "ЗАБЛОКИРОВАН"
    if gate >= 85:
        return "готов"
    if gate >= 65:
        return "готов с оговорками"
    return "не готов"


def report(agent: Path, as_json: bool = False, cards_dir: Path | None = None,
           kb_dir: Path | None = None) -> int:
    axes, blocks = assess(agent, cards_dir, kb_dir)
    gauge, gate = score_of(axes, blocks)
    if as_json:
        print(json.dumps({"агент": agent.name, "шкала": gauge, "ворота": gate,
                          "полоса": band(gate, blocks), "блокировки": blocks,
                          "оси": {a.key: a.score for a in axes}},
                         ensure_ascii=False, indent=2))
        return 1 if blocks else 0
    print("=" * 68)
    print(f"КОНТЕКСТ: {agent.name}")
    print("=" * 68)
    for a in axes:
        print(f"\n{a.name} — {a.score:.0f}")
        print(f"  ({a.why})")
        for name, ok, detail in a.checks:
            print(f"  {'✔' if ok else '✘'} {name}" + (f"  · {detail}" if detail and not ok else ""))
    print("\n" + "-" * 68)
    print(f"ШКАЛА {gauge}  ·  ВОРОТА {gate}  ·  {band(gate, blocks)}")
    if blocks:
        print("\nБЛОКИРОВКИ (не усредняются):")
        for b in blocks:
            print(f"  ✘ {b}")
        print("\nПосле блокировки ворота не двигаются. Улучшение от версии")
        print("к версии видно только по шкале — поэтому обе цифры показываются.")
    return 1 if blocks else 0


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("path", type=Path)
    ap.add_argument("--json", action="store_true")
    ap.add_argument("--все", dest="all", action="store_true",
                    help="папка портфеля: оценить каждого агента")
    ap.add_argument("--карточки", dest="cards", type=Path, default=None,
                    help="папка с описаниями агентов, если карточки лежат отдельно")
    ap.add_argument("--база", dest="kb", type=Path, default=None,
                    help="папка базы знаний, если она лежит отдельно от пакета "
                         "(норма для портфеля: пакет — ZIP, база — в пространстве)")
    a = ap.parse_args()
    if not a.path.is_dir():
        print(f"нет такой папки: {a.path}")
        return 2
    if not a.all:
        return report(a.path, a.json, a.cards, a.kb)
    # База знаний — ПОАГЕНТНАЯ.
    #
    # Прежде `--база` передавалась каждому агенту как есть, и если она указывала
    # на общую папку баз знаний портфеля, оси считались по объединённому
    # содержимому всех баз сразу. Замер «все пятеро 100,0» был завышен: за ним
    # прятались четыре настоящих пробела — незаданная единица результата,
    # отсутствие строки сверки, поведение при отказе, вынос расхождения человеку.
    # Режим `--все` — ровно тот, которым меряют портфель, то есть завышал он
    # там, где на него и смотрят.
    def база_агента(d: pathlib.Path):
        if a.kb is None or not a.kb.is_dir():
            return a.kb
        свои = [k for k in sorted(a.kb.iterdir()) if k.is_dir()]
        ном = re.match(r"(\d+)", d.name)
        слаг = re.sub(r"^\d+[_\- ]*", "", d.name).lower()
        for k in свои:
            имя = k.name.lower()
            if (ном and имя.startswith(ном.group(1) + "_")) or (слаг and слаг[:12] in имя):
                return k
        return a.kb if not свои else None

    rows = []
    без_базы = []
    for d in sorted(a.path.iterdir()):
        if not d.is_dir():
            continue
        kb = база_агента(d)
        if kb is None:
            без_базы.append(d.name)
        axes, blocks = assess(d, a.cards, kb)
        g, gt = score_of(axes, blocks)
        rows.append((d.name, g, gt, band(gt, blocks), {x.key: x.score for x in axes}))
    первый = next(d for d in sorted(a.path.iterdir()) if d.is_dir())
    keys = [x.key for x in assess(первый, a.cards, база_агента(первый))[0]]
    print(f"{'агент':<30} {'шкала':>6} {'ворота':>7}  " + " ".join(f"{k[:5]:>5}" for k in keys))
    print("-" * 96)
    for name, g, gt, b, ax in rows:
        print(f"{name[:29]:<30} {g:>6} {gt:>7}  " + " ".join(f"{ax[k]:>5.0f}" for k in keys) + f"  {b}")
    if без_базы:
        print("\nБЕЗ СВОЕЙ БАЗЫ ЗНАНИЙ: " + ", ".join(без_базы))
        print("Оценка этих агентов считалась без базы знаний. Считать её по "
              "общей папке нельзя: так оси берут содержимое всех баз сразу и "
              "оценка портфеля завышается — это уже случилось.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
