def _shuffle_cmds(t: str) -> str:
    head, *blocks = re.split(r"(?=^## )", t, flags=re.M)
    return head + "".join(reversed(blocks))


def _reflow_paragraphs(t: str) -> str:
    """Склеивает строки внутри абзаца, сохраняя заголовки отдельными строками."""
    out = []
    for block in t.split("\n\n"):
        lines = block.split("\n")
        if any(l.strip().startswith("#") for l in lines):
            out.append(block)
        else:
            out.append(" ".join(l.strip() for l in lines if l.strip()))
    return "\n\n".join(out)


def _comment_noise(t: str) -> str:
    return re.sub(r"^(## .+)$", r"\n<!-- комментарий -->\n\1\n", t, flags=re.M)


RELATIONS = [
    ("порядок команд не влияет на вердикт",
     lambda s, c, m: (s, c, _shuffle_cmds(m))),
    ("согласованное переименование не влияет",
     lambda s, c, m: (s.replace("demo-agent", "demo-bot"),
                      c.replace("demo-agent", "demo-bot"), m)),
    ("служебные комментарии не влияют",
     lambda s, c, m: (s, c, _comment_noise(m))),
    ("NFD-нормализация текста не влияет",
     lambda s, c, m: tuple(unicodedata.normalize("NFD", x) for x in (s, c, m))),
    # Переразбивка склеивает строки ВНУТРИ абзаца, но не через границу
    # заголовка: транформ, склеивающий «## Инструкция» с телом, ломает
    # markdown-структуру и потому не является косметическим — ожидать от
    # него инвариантности некорректно.
    ("переразбивка строк внутри абзацев не влияет",
     lambda s, c, m: (s, _reflow_paragraphs(c), m)),
    ("дубли команд не создают новых классов ошибок",
     lambda s, c, m: (s, c, m + "\n" + _shuffle_cmds(m).split("\n", 1)[1])),
]


