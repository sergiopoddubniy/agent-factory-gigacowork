def block_differential(kit: Path, kb: Path | None) -> None:
    """Прогон по реальному поставленному киту. Ожидание — PASS: артефакт
    работает у клиента, значит проверки, которые на нём падают, неверны."""
    print(f"\nДИФФЕРЕНЦИАЛЬНЫЙ ТЕСТ: {kit.name}")
    inner = kit
    if not (inner / "SKILL.md").exists():
        subs = [d for d in kit.iterdir() if d.is_dir() and (d / "SKILL.md").exists()]
        if subs:
            inner = subs[0]
    skill = inner / "SKILL.md"
    card = next(iter(sorted(inner.glob("01_Агент*.md"))), None)
    cmds = next(iter(sorted(inner.glob("0[23]_Команды*.md"))), None)
    if not (skill.exists() and card and cmds):
        check("кит распознан (SKILL.md + 01_Агент + 0N_Команды)", False,
              f"найдено: {[p.name for p in inner.iterdir()]}")
        return
    check("кит распознан (SKILL.md + 01_Агент + 0N_Команды)", True)

    # Номер агента живёт на ВНЕШНЕЙ папке кита (`2_tender-docs-analyst/`),
    # а внутренняя — просто slug. Брать номер из внутренней значит молча
    # пропустить проверку префикса команд на всех боевых китах: она
    # включается только при заданном номере.
    number, slug = None, inner.name
    for cand in (inner.name, kit.name, kit.resolve().parent.name):
        m = re.match(r"(\d+)_(.+)", cand)
        if m:
            number, slug = m.group(1), m.group(2)
            break
    check("номер агента определён (иначе проверка префикса не выполняется)",
          number is not None, f"кит={kit.name}, внутренняя={inner.name}")
    fx = {"dir": Path(tempfile.mkdtemp(prefix="diff_")), "skill": skill,
          "card": card, "cmds": cmds, "kb": kb}
    rc, ids = run_card(fx, number=number, slug=slug)
    blocking = {i for i in ids if i not in ("NUMBER_DRIFT", "SECTION_ORDER_BROKEN")}
    check("поставленный кит проходит проверки", rc == 0 and not blocking,
          f"rc={rc}, findings={sorted(ids)}")
    if rc != 0 or blocking:
        print("      Разбирать обязательно: либо кит и правда собран неверно, "
              "либо проверка неверна сама. Второе вероятнее, если кит работает "
              "у клиента.")


