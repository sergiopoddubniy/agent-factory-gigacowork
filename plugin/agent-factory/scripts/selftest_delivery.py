#!/usr/bin/env python3
"""
selftest.py — самопроверка скилла и его инструментов перед выдачей.

Зачем. Проверки деградируют тише, чем проверяемое: сломанный детектор
рапортует «всё чисто». Из 37 дефектов, найденных при аудите этого скилла,
11 были дефектами самих проверок — семь проходили вхолостую, четыре падали
на корректном входе. Этот файл фиксирует найденное, чтобы следующая правка
не сломала его молча.

Три независимых блока, каждый ловит свой класс:

  СВЯЗАННОСТЬ — ссылки между файлами скилла резолвятся, термины определены,
                нумерация режимов не коллидирует.
  МУТАЦИИ     — намеренно ломаем вход по одному признаку и убеждаемся, что
                нужная проверка срабатывает. Ловит ОТСУТСТВУЮЩИЕ проверки.
  МЕТАМОРФНЫЕ — вердикт не меняется от того, от чего он зависеть не должен
                (порядок команд, оформление, юникод-нормализация). Ловит
                ЛОЖНЫЕ СРАБАТЫВАНИЯ, которые мутации не видят в принципе.

Запуск:

    python3 scripts/selftest.py                 # всё на синтетических фикстурах
    python3 scripts/selftest.py --only links    # links | mutations | metamorphic
    python3 scripts/selftest.py --against <путь к поставленному киту> [--kb <база>]

Флаг --against — дифференциальный тест: прогон проверок по киту, который
уже поставлен клиенту и работает. Самый результативный из применённых
методов и единственный, находящий дефекты в самих правилах: проверка,
падающая на боевом артефакте, почти всегда неверна сама. Держи один
поставленный кит как эталонную фикстуру и прогоняй по нему после каждой
правки проверок.

Код возврата: 0 — всё зелёно, 1 — есть провалы.
Зависимостей нет, фикстуры генерируются на лету.
"""

