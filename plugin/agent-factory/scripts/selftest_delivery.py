def block_context_budget() -> None:
    """Скилл — это тоже контекст, и он подчиняется тем же правилам.

    Незакрытый блок кода ломает разбор всего, что идёт после него: агент
    читает остаток файла как код. Проверка дешёвая и ловит поломку, которую
    глазами не видно.

    Размер проверяется отдельным скриптом `scripts/token_budget.py` — здесь
    только наличие инструмента и отсутствие поломок разметки.
    """
    print("\nБЮДЖЕТ КОНТЕКСТА")
    check("инструмент замера бюджета существует",
          (ROOT / "scripts" / "token_budget.py").exists(),
          "размер скилла обнаруживается замером, а не на встрече")

    bad = []
    for p in [ORCH, *sorted(REFS.glob("*.md"))]:
        txt = p.read_text(encoding="utf-8")
        if len(re.findall(r"^```", txt, re.M)) % 2 or len(re.findall(r"^~~~", txt, re.M)) % 2:
            bad.append(p.name)
    check("нет незакрытых блоков кода", not bad,
          "незакрытый блок превращает весь остаток файла в код для агента: "
          + ", ".join(bad[:3]))

    # Директивность: скилл должен предписывать, а не советовать.
    STRONG = r"обязательн|должен|должна|должно|нельзя|запрещ|всегда|никогда|требуется"
    WEAK = r"можно|стоит|желательн|при необходимости|как правило|обычно|рекомендуется"
    sk_low = orchestrator_text().lower()
    s, w = len(re.findall(STRONG, sk_low)), len(re.findall(WEAK, sk_low))
    ratio = s / (s + w) if s + w else 0
    check(f"язык директивный, а не совещательный ({ratio:.2f})", ratio >= 0.6,
          "исполнитель следует предписанию и пропускает пожелание; "
          f"сильных маркеров {s}, слабых {w}")


