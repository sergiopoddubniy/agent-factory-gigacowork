def block_scripts_no_shadow() -> None:
    """Две функции с одним именем в модуле: вторая молча съедает первую.

    Так в реестре чуть не разошлись `токены()` для BM25 и одноимённая функция
    сопоставления имён: поиск получил бы множество вместо списка и потерял
    частоты — при полностью зелёном selftest. Это тот же дефект «два описания
    одного и того же», только в коде, и заметен он лишь на выходе поиска.
    """
    print("\nСКРИПТЫ: НЕТ ПЕРЕКРЫТЫХ ОПРЕДЕЛЕНИЙ")
    import ast
    for p in sorted((ROOT / "scripts").glob("*.py")):
        try:
            дерево = ast.parse(p.read_text(encoding="utf-8"))
        except SyntaxError as e:
            check(f"{p.name}: разбирается", False, str(e))
            continue
        имена: dict[str, int] = {}
        дубли = []
        for узел in дерево.body:
            if isinstance(узел, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                if узел.name in имена:
                    дубли.append(f"{узел.name} (строки {имена[узел.name]} и {узел.lineno})")
                имена[узел.name] = узел.lineno
        check(f"{p.name}: имена верхнего уровня не повторяются",
              not дубли,
              "перекрыто: " + "; ".join(дубли) + " — работает последнее "
              "определение, а вызовы написаны под первое")


