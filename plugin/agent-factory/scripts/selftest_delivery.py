def block_gates_tell_truth() -> None:
    """Стенд, всегда возвращающий 0, — не ворота, а отчёт.

    Найдено ежедневной задачей 26.08: `mutate_landed.py` печатал
    «не ловится: N» и всегда завершался с кодом 0. Любой внешний запуск —
    регулярная задача, CI, чужой прогон — видел успех при выживших мутантах.
    Рядом `token_budget.py` и `audit_findings.py` на красном честно
    возвращали 1, и на контрасте это было видно.

    Проверка разбирает синтаксическое дерево: у каждого стенда должен быть
    выход с НЕконстантным условием. Это проверка формы, а не поведения, и
    она названа так честно: поведение проверяется прогоном стенда с заведомо
    выжившим мутантом, и такой прогон слишком дорог, чтобы держать его здесь.
    """
    import ast
    print("\nВОРОТА ГОВОРЯТ ПРАВДУ")
    for name in ("mutate_landed.py", "mutate_budget.py", "mutate_build.py"):
        f = SCRIPTS / name
        if not f.exists():
            check(f"{name}: стенд на месте", False, "стенда нет")
            continue
        tree = ast.parse(f.read_text(encoding="utf-8"))
        exits = [n for n in ast.walk(tree)
                 if isinstance(n, ast.Call)
                 and isinstance(n.func, ast.Attribute) and n.func.attr == "exit"]
        conditional = [e for e in exits if e.args
                       and not isinstance(e.args[0], ast.Constant)]
        check(f"{name}: код возврата зависит от результата", bool(conditional),
              "стенд завершается всегда одинаково — выживший мутант "
              "не отличим от чистого прогона")
        src = f.read_text(encoding="utf-8")
        check(f"{name}: неприменённая мутация считается провалом",
              "unapplied" in src and "unapplied)" in src.replace(" ", ""),
              "мутация, которая не применилась, молча уходит из знаменателя — "
              "доля отлова растёт от того, что мутанта не испытали")

    # Путь стенда не должен быть прибит к чужой песочнице: такой стенд
    # переживает сессию только у автора, а у всех остальных падает до первой
    # мутации и выглядит как сломанный скрипт.
    for name in ("mutate_landed.py", "mutate_budget.py", "mutate_build.py"):
        f = SCRIPTS / name
        if not f.exists():
            continue
        src = f.read_text(encoding="utf-8")
        check(f"{name}: корень берётся от файла, а не абсолютным путём",
              "Path(__file__)" in src or "pathlib.Path(__file__)" in src,
              "прибитый путь песочницы пережил сессию: стенд падал у всех, "
              "кроме автора")


