    print("\nГРАНИЦА С feo-ai-methodology")
    чит = lambda p: p.read_text(encoding="utf-8", errors="replace")
    плоско = lambda s: re.sub(r"[ \t]*\n[ \t]*", " ", s)
    sk = orchestrator_text()
    dc = чит(REFS / "delivery_composition.md")
    cd = чит(SCRIPTS / "check_delivery.py")

