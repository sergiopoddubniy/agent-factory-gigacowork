def собрать_индекс(записи: list[dict]) -> str:
    по_клиентам: dict[str, list[dict]] = {}
    for z in записи:
        по_клиентам.setdefault(z["клиент"], []).append(z)
    строки = [
        "# Реализованные агенты — индекс",
        "",
        "> **Файл генерируется.** Единственный источник — `registry.yaml`.",
        "> Пересобрать: `python3 scripts/agent_registry.py --индекс`.",
        "",
        f"Всего агентов: **{len(записи)}** у {len(по_клиентам)} клиентов.",
        "",
        "Зачем этот файл: перед проектированием нового агента посмотреть,",
        "не собран ли похожий. Если собран — запросить доступ к его папке и",
        "переиспользовать, а не воспроизводить по памяти.",
        "",
    ]
    for клиент, лист in sorted(по_клиентам.items()):
        строки += [f"## {клиент}", "",
                   "| id | Агент | Джоба | Коннектор | Эффект |",
                   "|---|---|---|---|---|"]
        for z in sorted(лист, key=lambda x: x["id"]):
            строки.append(
                f"| `{z['id']}` | {z['имя']} | {z.get('джоба') or '—'} | "
                f"{z.get('коннектор') or '—'} | {z.get('эффект', '—')} |")
        строки.append("")
    строки += [
        "---",
        "",
        "## Чего здесь нет",
        "",
        "Клиентских данных: цифр, текстов навыков, названий контрагентов.",
        "В реестре — метаданные и путь; содержимое живёт в папке клиента и",
        "берётся оттуда по запросу доступа.",
        "",
        "Подтверждённого эффекта, пока его не подтвердил человек со ссылкой",
        "на замер. `не подтверждён` — честное состояние, а не пробел.",
        "",
    ]
    return "\n".join(строки)


def похожие(запрос: str, записи: list[dict], k: int = 5):
    """BM25 по метаданным реестра."""
    # Роль и функция — по два-три слова против абзаца джобы, и BM25 их почти
    # не слышит: запрос «что есть для финансового директора» поднимал агента
    # маркетолога выше казначейского. Короткие поля повторяются, и это не
    # хитрость, а стандартный способ задать им вес.
    def если(z):
        части = [str(z.get(p, "")) for p in
                 ("имя", "джоба", "когда применять", "коннектор", "id")]
        части += [str(z.get("роль", ""))] * 4
        части += [str(z.get("функция", ""))] * 3
        return " ".join(части)
    docs = {z["id"]: токены(если(z)) for z in записи}
    if not docs:
        return []
    df = Counter()
    for ts in docs.values():
        df.update(set(ts))
    N = len(docs)
    avg = sum(len(t) for t in docs.values()) / N
    q = токены(запрос)
    очки = Counter()
    for ид, ts in docs.items():
        c, L = Counter(ts), len(ts) or 1
        s = 0.0
        for t in q:
            f = c.get(t)
            if not f:
                continue
            idf = math.log(1 + (N - df[t] + 0.5) / (df[t] + 0.5))
            s += idf * f * 2.2 / (f + 1.2 * (0.25 + 0.75 * L / avg))
        if s:
            очки[ид] = s
    по_id = {z["id"]: z for z in записи}
    return [(по_id[i], s) for i, s in очки.most_common(k)]


def полный_путь(z: dict):
    """Якорь + относительный путь. None, если якорь не смонтирован.

    Различать «якорь не смонтирован» и «пакет исчез» обязательно: первое —
    свойство сессии, второе — потеря артефакта. Свести их в одно сообщение
    значит приучить читателя пропускать оба.
    """
    якорь = найти_папку(z.get("якорь", "")) if z.get("якорь") else None
    if якорь is None:
        return None
    return якорь / z.get("путь", "")


def забыть(записи: list[dict], ид: str) -> tuple[list[dict], str]:
    """Убрать запись из реестра. Решение человека, а не скрипта.

    Комплект переезжает: у Клиент-М папка сменила адрес, и в реестре остались
    четыре записи, указывающие в пустоту, плюс четыре пары «одна джоба у
    нескольких агентов». Автоматически такие записи удалять нельзя — по пути
    может не быть просто потому, что папка не смонтирована в этой сессии, и
    молчаливое удаление стёрло бы историю. Поэтому отдельная команда.
    """
    было = len(записи)
    записи = [z for z in записи if z.get("id") != ид]
    if len(записи) == было:
        return записи, f"записи «{ид}» в реестре нет"
    return записи, f"убрана запись «{ид}»"


def lint(записи: list[dict]) -> list[str]:
    из_за = []
    по_джобе: dict[str, list[str]] = {}
    for z in записи:
        if not z.get("джоба"):
            из_за.append(f"{z['id']}: нет джобы — кейс не переиспользуется, "
                         "потому что непонятно, что он закрывает")
        полный = полный_путь(z)
        if полный is None:
            из_за.append(f"{z['id']}: якорь не смонтирован — «{z.get('якорь')}»; "
                         f"пакет ожидается в «{z.get('путь')}»")
        elif not полный.exists():
            из_за.append(f"{z['id']}: пакета нет по пути «{полный}»")
        if z.get("джоба"):
            по_джобе.setdefault(nameflat(z["джоба"])[:60], []).append(z["id"])
    for дж, ids in по_джобе.items():
        if len(ids) > 1:
            из_за.append("одна джоба у нескольких агентов: " + ", ".join(ids)
                         + " — либо это переиспользование и его надо назвать, "
                           "либо два агента делают одно и то же")
    # Запись, которую перестали обновлять, выглядит в реестре так же, как
    # свежая. Именно так выпадает клиент, чья папка лежит вне
    # просканированных путей: агенты в списке есть, а состояние их — прошлое.
    for z in записи:
        try:
            дней = (date.today() - date.fromisoformat(z.get("обновлено", ""))).days
        except (TypeError, ValueError):
            из_за.append(f"{z['id']}: нет даты обновления — неизвестно, "
                         "когда запись в последний раз сверялась с диском")
            continue
        if дней > ДАВНОСТЬ:
            из_за.append(f"{z['id']}: запись не обновлялась {дней} дн. — папка "
                         "клиента вне просканированных путей; реестр выдаёт "
                         "прошлое состояние за нынешнее")

    неподтв = [z["id"] for z in записи if z.get("эффект") == "не подтверждён"]
    if неподтв:
        из_за.append(f"эффект не подтверждён у {len(неподтв)} из {len(записи)} — "
                     "это не дефект реестра, а состояние дел: подтверждает "
                     "человек со ссылкой на замер")
    return из_за


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--сканировать", dest="scan", nargs="+", default=None)
    ap.add_argument("--похожие", dest="query", default=None)
    ap.add_argument("--индекс", dest="idx", action="store_true")
    ap.add_argument("--lint", dest="lint", action="store_true")
    ap.add_argument("--забыть", dest="forget", default=None,
                    metavar="ID", help="убрать запись: комплект переехал "
                                       "или клиент закрыт")
    a = ap.parse_args()
    if not (a.scan or a.query or a.idx or a.lint or a.forget):
        print(__doc__)
        return 2

    записи = загрузить()

    if a.forget:
        записи, сообщение = забыть(записи, a.forget)
        сохранить(записи)
        ИНДЕКС.write_text(собрать_индекс(записи), encoding="utf-8")
        ЖУРНАЛ.write_text(
            (ЖУРНАЛ.read_text(encoding="utf-8") if ЖУРНАЛ.exists()
             else "# Журнал сканирований реестра\n")
            + f"\n## {date.today().isoformat()}\n\n- {сообщение} (решение человека)\n",
            encoding="utf-8")
        print(сообщение)
        return 0

    if a.scan:
        новые, замечания = сканировать(a.scan)
        записи, события = слить(записи, новые)
        сохранить(записи)
        ИНДЕКС.write_text(собрать_индекс(записи), encoding="utf-8")
        строка = (f"\n## {date.today().isoformat()}\n\n"
                  f"Просканировано папок: {len(a.scan)}; агентов в реестре: "
                  f"{len(записи)}.\n\n"
                  + ("\n".join(f"- {e}" for e in события) or "- изменений нет")
                  + ("\n" + "\n".join(f"- ! {z}" for z in замечания)
                     if замечания else "") + "\n")
        ЖУРНАЛ.write_text(
            (ЖУРНАЛ.read_text(encoding="utf-8") if ЖУРНАЛ.exists()
             else "# Журнал сканирований реестра\n") + строка, encoding="utf-8")
        print(f"агентов в реестре: {len(записи)}")
        for e in события:
            print(f"  · {e}")
        for z in замечания:
            print(f"  ! {z}")

    if a.idx and not a.scan:
        ИНДЕКС.write_text(собрать_индекс(записи), encoding="utf-8")
        print(f"ИНДЕКС.md пересобран: {len(записи)} записей")

    if a.query:
        найдено = похожие(a.query, записи)
        print(f"\nПОХОЖИЕ НА «{a.query}» — {len(найдено)}")
        if not найдено:
            print("  ничего близкого; собирается с нуля")
        for z, s in найдено:
            print(f"\n  [{s:5.1f}] {z['id']} — {z['имя']}")
            print(f"          клиент: {z['клиент']} · коннектор: "
                  f"{z.get('коннектор') or '—'}")
            print(f"          джоба: {z.get('джоба') or '—'}")
            полный = полный_путь(z)
            если_нет = (f"{z['путь']}  (якорь не смонтирован: "
                        f"{z.get('якорь')})")
            print(f"          путь: {полный if полный else если_нет}")
        if найдено:
            print("\n  Прежде чем собирать нового: назовите эти агенты "
                  "пользователю\n  и запросите доступ к их папкам. "
                  "Воспроизводить чужой пакет\n  по памяти нельзя — получится "
                  "похоже и неверно.")

    if a.lint:
        замечания = lint(записи)
        print(f"\nLINT — {len(замечания)}")
        for z in замечания:
            print(f"  · {z}")
        return 1 if замечания else 0
    return 0


if __name__ == "__main__":
    sys.exit(main())
