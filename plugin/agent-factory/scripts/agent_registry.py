"""Реестр реализованных агентов: что уже сделано и где это лежит.

    python3 agent_registry.py --сканировать "<папка клиента>" ["<ещё>" …]
    python3 agent_registry.py --похожие "рассчитать ставку перевозки"
    python3 agent_registry.py --индекс
    python3 agent_registry.py --lint

Код возврата: 0 — порядок; 1 — lint нашёл замечания либо сканировать нечего.

**Зачем.** Контур дефектов у нас построен: находка из проекта клиента уезжает
в бэклог. Контур **активов** не был построен вовсе — за четыре клиента ни
одной записи о том, какой агент какую джобу закрыл, каким коннектором ходил и
где лежит его пакет. Из-за этого следующий похожий агент проектируется с нуля,
хотя рядом лежит собранный.

**Что этот скрипт делает.** Обходит папки клиентов, находит агентов по
`id` в навыке, забирает **метаданные**: id, имя, джоба, коннектор, клиент,
путь, версия комплекта. Складывает в `references/knowledge/registry.yaml` —
единственный источник; `ИНДЕКС.md` генерируется из него.

**Чего он не делает и почему.**

- **Не копирует артефакты.** Записывается путь, а не содержимое: копия в
  реестре разойдётся с оригиналом при первой правке — этот дефект у нас уже
  был, и не один раз.
- **Не переносит клиентские данные.** В реестр идут метаданные: джоба словами
  роли, коннектор, отрасль. Цифры клиента, тексты навыков, названия
  контрагентов остаются в папке клиента.
- **Никогда не заполняет поле «эффект».** `эффект: не подтверждён` ставится
  всегда; изменить может только человек и только со ссылкой на замер. На этот
  показатель ссылаются в продаже, и цена подделки здесь выше, чем у любого
  другого поля.

**Как этим пользуется агент сборки.** На Стадии 0, до проектирования:
`--похожие "<джоба клиента>"`. Если находится близкий агент — он называется
пользователю вместе с путём, и **запрашивается доступ к папке**. Воспроизводить
чужой пакет по памяти нельзя: получится похоже и неверно.
"""
