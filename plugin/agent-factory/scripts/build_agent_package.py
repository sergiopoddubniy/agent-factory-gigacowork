def _criteria_table(items: list) -> str:
    """Критерии закрытия — по одному на пункт, описаны один раз (output_stability,
    уровень 4: неоднозначность решена заранее, а не в момент ответа)."""
    rows = ["| № | Пункт чек-листа | `закрыто`, если |", "|---|---|---|"]
    rows += [f"| {i} | {it} | {crit or DEFAULT_CRITERION} |" for i, (it, crit) in enumerate(items, 1)]
    return "\n".join(rows)


def _checklist_table(items: list) -> str:
    """Таблица чек-листа полноты — единица результата для реестра вопросов.
    Форма описывается здесь один раз; остальные разделы на неё ссылаются
    (output_stability, уровень 5: пересказанная форма теряет хвост)."""
    n = len(items)
    rows = ["| № | Пункт чек-листа | Статус | Якорь (фрагмент письма / объект выгрузки) | Вопрос № |",
            "|---|---|---|---|---|"]
    rows += [f"| {i} | {it} | {CHECKLIST_STATUSES} | <цитата или «—»> | <номер или «—»> |"
             for i, (it, _) in enumerate(items, 1)]
    rows.append("")
    rows.append(f"Чек-лист: {n} пунктов · закрыто K · вопросов Q · конфликтов C · K+Q+C={n}")
    return "\n".join(rows)


def _checklist_module(items: list) -> str:
    n = len(items)
    return (f"**Модуль 0. Опись по чек-листу полноты (первый проход, до анализа).** "
            f"Пройти {n} пунктов чек-листа §8 по порядку, сверху вниз, не переходя к следующему, "
            f"пока не заполнен предыдущий; на каждый — ровно одна строка таблицы: статус "
            f"{CHECKLIST_STATUSES} и якорь в источнике. Статус `закрыто` — только когда выполнен "
            f"критерий закрытия этого пункта из таблицы критериев §8; если источник упоминает "
            f"пункт косвенно или его можно лишь вывести — `вопрос`. Выход: таблица из {n} строк и строка "
            f"сверки. Stop condition: число строк ≠ {n} или K+Q+C ≠ {n} → результат не выдаётся "
            f"как полный, показывается «обработано K+Q+C из {n}» и перечень необработанного.")


def _modules(spec: Spec) -> list:
    st = steps(spec.block(8))
    ins, outs = io_lists(spec.block(6))
    cl = checklist_items(spec.block(8))
    head = [_checklist_module(cl)] if cl else []
    if st:
        mods = list(head) + [
            "Для каждого модуля ниже: проверки — полнота входа и соответствие правилам §7; stop "
            "condition — отсутствие обязательного входа → `missing_data`, конфликт источников → "
            "`conflict_requires_review`. Модуль, помеченный «ветвь», выполняется только при своём "
            "условии; вход у него — результат точки ветвления, а не соседней ветви."]
        prev_out = "входные данные §5" + (" и таблица чек-листа (модуль 0)" if cl else "")
        branch_out = prev_out          # выход последнего модуля, не являющегося ветвью
        for i, s in enumerate(st, 1):
            # Шаг может нести свой выход после стрелки: «…сделать → что получилось».
            action, _, output = s.partition("→")
            action, output = action.strip().rstrip("."), output.strip().rstrip(".")
            output = output or "проверяемый промежуточный результат шага"
            is_branch = bool(re.match(r"^(при\b|если\b|иначе\b|когда\b|в случае\b)", action, re.I))
            inp = branch_out if is_branch else prev_out
            mods.append(f"**Модуль {i}{' (ветвь)' if is_branch else ''}.** {action}.\n"
                        f"  - вход: {inp}\n  - выход: {output}")
            prev_out = f"выход модуля {i} ({output})"
            if not is_branch:
                branch_out = prev_out
        return mods
    return head + [
        f"**Модуль 1. Приём входов.** Вход: {', '.join(ins) if ins else 'входные документы'}. "
        "Выход: реестр полученного с пометкой, чего не хватает (`missing_data`). "
        "Stop condition: нет ни одного обязательного входа → уточняющий вопрос, работа не начинается.",
        "**Модуль 2. Применение правил.** Вход: реестр входов. Выход: результат по каждому правилу §7 "
        "с признаком, порогом и источником. Проверка: каждый вывод имеет источник во входных данных.",
        "**Модуль 3. Сверка и неопределённость.** Противоречия между источниками → "
        "`conflict_requires_review`; уверенность ниже порога → эскалация по §10/§11.",
        f"**Модуль 4. Формирование результата.** Выход: {', '.join(outs) if outs else 'результат по формату §8'} "
        "в формате §8. Проверка: все поля формата заполнены или помечены `missing_data`.",
        "**Модуль 5. Самопроверка.** Прогон quality gates §14 до выдачи ответа.",
    ]


def confirmed_tools(spec: Spec) -> str:
    """Подтверждённые инструменты команды запуска (`confirmed_tools` платформы) —
    из блока 11: «Коннекторы:» и «Навыки пространства:». Пусто или «нет» — «нет»."""
    b11 = spec.block(11)
    items = [f"коннектор «{c['name']}»" + (f" ({c['what']})" if c["what"] else "") for c in connectors(b11)]
    items += [f"навык пространства «{w['name']}»" for w in workspace_skills(b11)]
    return "; ".join(items) if items else "нет"


