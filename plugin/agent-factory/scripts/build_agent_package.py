def _cases(spec: Spec) -> str:
    b12 = spec.block(12)
    bullets = b12.bullets()
    ids = case_ids(b12)
    lines = list(bullets)
    for req in REQUIRED_CASES:
        if req not in ids:
            lines.append(f"`{req}` — Вход: см. схему спецификации → Ожидание: поведение по §10–§13.")
    return "\n".join(f"- {x}" for x in lines)


def _hitl(spec: Spec) -> str:
    rows = hitl_rows(spec.block(10))
    if not rows:
        return ("Точки валидации человеком не заданы в спецификации; действует правило по умолчанию: "
                "любое внешнее действие и любой вывод с низкой уверенностью → `HITL_REQUIRED`.")
    out = ["| Точка | Кто | Критерий | Что блокирует | Эскалация |", "|---|---|---|---|---|"]
    out += ["| " + " | ".join(r[:5]) + " |" for r in rows]
    out.append("")
    out.append("`HITL_REQUIRED` ставится в каждой точке таблицы: агент останавливается, излагает "
               "найденное полностью и ждёт решения названной роли. Внешних действий без "
               "подтверждения нет.")
    return "\n".join(out)


def _mode0(spec: Spec, num: int) -> str:
    """Фиксированный ответ Режима 0 — пять блоков (agent_package.md, «Команда
    „Как со мной работать“»). Читается за минуту; длинное — в точке входа комплекта."""
    ins, outs = io_lists(spec.block(6))
    inside, outside = scope_lists(spec.block(7))
    role = spec.block(5).field_value("Роль") or "пользователя"
    job = ("для роли «" + role + "»: " + "; ".join(inside)) if inside else "работа по §1"
    cmds = all_commands(spec, num)
    return "\n".join([
        "```text", f"Что я делаю: {job}.",
        "Что мне дать: " + ("; ".join(ins) if ins else "входные документы по §5") + ".",
        "Что вы получите: " + ("; ".join(outs) if outs else "результат по §8") + " — в этом чате, по форме §17.",
        "Чего я не делаю: " + ("; ".join(outside) if outside else "запросы вне периметра §3") + ". Решение остаётся за вами.",
        "Мои команды: " + "; ".join(f"{c['num']} {c['name']} — {c['desc']}" for c in cmds) + ".",
        "```"])


