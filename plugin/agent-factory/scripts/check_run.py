#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Вердикт по приёмочному прогону развёрнутого агента.

    python3 check_run.py --кейсы <evals_*.md> --прогон <прогон_*.md>
    python3 check_run.py --самопроверка

Код возврата: 0 — все блокирующие кейсы пройдены; 1 — провален блокирующий
кейс либо на блокирующий кейс нет ответа; 2 — файлы не разобраны.

**Зачем инструмент, если ответы читает человек.** Уровень «развёрнутый агент»
до сих пор был единственным, у которого не было измерителя. Комплект на диске
проверяет `check_delivery.py`, пакет — `build_agent_package.py`, сам скилл —
`selftest.py`; агент, уже стоящий в пространстве, проверялся глазами, и
результат жил в голове проверяющего. Правило скилла на этот счёт прямое:
проверка, у которой нет своего уровня, не существует.

**Почему прогон всё равно ручной.** Агент живёт в пространстве GigaCowork, и
позвать его из скрипта нельзя. Поэтому прогон делится надвое: человек задаёт
вопросы и вставляет ответы в файл прогона, машина выносит вердикт. Разделение
не формальность — оно убирает ровно то место, где прогон обычно и ломается:
«ну, в целом ответил правильно».

**Признаки смотрят на артефакт, а не на впечатление.** Есть ли таблица и
сколько в ней строк; стоит ли имя навыка русскими буквами; есть ли ссылка;
не появилось ли запрещённое слово. Признак, который нельзя проверить
подстрокой, числом или структурой, в набор не попадает — иначе вердикт
возвращается к оценке на глаз, а вместе с ним и разброс.

**Чего измеритель не измеряет.** Он не судит о качестве разбора по существу:
вердикт «пройден» означает, что в ответе есть обязательные элементы, а не что
ответ хорош. Полезность проверяется человеком и прогонами на реальных
задачах; здесь проверяется, что версия внедрена и поведение не откатилось.
"""
from __future__ import annotations

import argparse
import re
import sys
import unicodedata
from pathlib import Path

# ─────────────────────────── нормализация ───────────────────────────
#
# Для текста и для имён файлов нужны РАЗНЫЕ функции: normalize, схлопывающая
# пробелы, уничтожает переводы строк, а по ним ищется первая строка ответа и
# границы таблицы. Здесь два уровня: `nfc` — только форма Unicode, `плоско` —
# сравнение подстрок.


def nfc(s: str) -> str:
    return unicodedata.normalize("NFC", s)


def плоско(s: str) -> str:
    """Для сравнения подстрок: NFC, нижний регистр, схлопнутые пробелы.

    Кавычки и дефисы приводятся к одному виду: «ёлочки», „лапки“ и прямые
    кавычки в ответе агента встречаются вперемешку, и признак, различающий
    их, проверяет клавиатуру, а не поведение.
    """
    s = nfc(s).lower().replace("ё", "е")
    s = re.sub(r"[«»„“”\"'`]", "\"", s)
    s = re.sub(r"[–—−]", "-", s)
    s = re.sub(r"\s+", " ", s)
    return s.strip()


# ─────────────────────────── разбор файлов ───────────────────────────

ЗАГОЛОВОК_КЕЙСА = re.compile(r"^#{2,4}\s*([БОС]-[\w.\-]+?)\s*(?:·.*)?$", re.M)
# «С-» — кейсы, ждавшие коннектора. Они наблюдательные, но существуют:
# набор, где такой кейс невидим измерителю, выглядит короче, чем он есть.
ПРИЗНАКИ = re.compile(r"\*\*Признаки:?\*\*\s*\n(.*?)(?=\n\s*\n|\Z)", re.S)
СТРОКА_ПРИЗНАКА = re.compile(r"^\s*[-*]\s*([а-яa-z\-]+(?:>=)?)\s*:\s*(.+?)\s*$", re.M | re.I)


def кейсы_из(текст: str) -> list[dict]:
    """Разбирает набор кейсов. Кейс без блока «Признаки» — не кейс.

    Осознанно жёстко: кейс, у которого признаки описаны прозой, выглядит в
    наборе как полноценный и молча не проверяется ничем. Такой кейс лучше
    видеть в списке ошибок разбора, чем в зелёном отчёте.
    """
    текст = nfc(текст)
    метки = list(ЗАГОЛОВОК_КЕЙСА.finditer(текст))
    out = []
    for i, m in enumerate(метки):
        кон = метки[i + 1].start() if i + 1 < len(метки) else len(текст)
        тело = текст[m.start():кон]
        ид = m.group(1).strip()
        бл = ПРИЗНАКИ.search(тело)
        признаки = []
        if бл:
            for п in СТРОКА_ПРИЗНАКА.finditer(бл.group(1)):
                признаки.append((п.group(1).lower(), п.group(2)))
        загол = тело.split("\n", 1)[0].lstrip("# ").strip()
        out.append({
            "id": ид,
            "имя": загол,
            "блокирующий": ид.startswith("Б"),
            "признаки": признаки,
        })
    return out


def ответы_из(текст: str) -> dict[str, str]:
    """Файл прогона: заголовок с идентификатором кейса, дальше ответ целиком."""
    текст = nfc(текст)
    метки = list(ЗАГОЛОВОК_КЕЙСА.finditer(текст))
    out = {}
    for i, m in enumerate(метки):
        кон = метки[i + 1].start() if i + 1 < len(метки) else len(текст)
        тело = текст[m.end():кон].strip("\n")
        out[m.group(1).strip()] = тело
    return out


# ─────────────────────────── признаки ───────────────────────────
#
# Язык намеренно маленький. Каждый признак обязан проверяться подстрокой,
# счётом или структурой ответа: как только в языке появляется «оцени», вердикт
# перестаёт быть воспроизводимым, и два человека на одном ответе получают
# разные результаты.


def _строки_таблицы(ответ: str) -> int:
    строки = [l.strip() for l in ответ.split("\n")]
    лучший = 0
    i = 0
    while i < len(строки):
        if строки[i].startswith("|") and i + 1 < len(строки) \
                and re.fullmatch(r"\|?[\s:|-]+\|[\s:|-]*", строки[i + 1] or ""):
            j, n = i + 2, 0
            while j < len(строки) and строки[j].startswith("|"):
                n += 1
                j += 1
            лучший = max(лучший, n)
            i = j
        else:
            i += 1
    return лучший


def _первые_строки(ответ: str, сколько: int = 3) -> str:
    непустые = [l for l in ответ.split("\n") if l.strip()]
    return " ".join(непустые[:сколько])


ПРОВЕРКИ = {
    "есть": lambda о, з: плоско(з) in плоско(о),
    "нет": lambda о, з: плоско(з) not in плоско(о),
    "есть-любое": lambda о, з: any(плоско(ч) in плоско(о) for ч in з.split("|")),
    "есть-все": lambda о, з: all(плоско(ч) in плоско(о) for ч in з.split("|")),
    "первая-строка-содержит":
        lambda о, з: any(плоско(ч) in плоско(_первые_строки(о))
                         for ч in з.split("|")),
    "строк-таблицы>=": lambda о, з: _строки_таблицы(о) >= int(з),
    "ссылок>=": lambda о, з: len(re.findall(r"https?://\S+", о)) >= int(з),
    "цитат>=": lambda о, з: len(re.findall(r"[«\"][^«»\"]{8,}[»\"]", nfc(о))) >= int(з),
    "чисел>=": lambda о, з: len(re.findall(r"\d[\d\s.,]*", о)) >= int(з),
    "процентов-нет": lambda о, з: not re.search(r"[+]\s*\d+\s*%", о),
}


def проверить_кейс(кейс: dict, ответ: str | None) -> tuple[bool, list[str]]:
    if ответ is None:
        return False, ["ответа нет в файле прогона"]
    if not кейс["признаки"]:
        return False, ["у кейса нет машинных признаков — проверить нечем"]
    провалы = []
    for имя, значение in кейс["признаки"]:
        f = ПРОВЕРКИ.get(имя)
        if f is None:
            провалы.append(f"неизвестный признак «{имя}»")
            continue
        try:
            ок = f(ответ, значение)
        except ValueError:
            провалы.append(f"признак «{имя}»: ожидалось число, пришло «{значение}»")
            continue
        if not ок:
            провалы.append(f"{имя}: {значение}")
    return (not провалы), провалы


# ─────────────────────────── прогон ───────────────────────────

def прогнать(кейсы: list[dict], ответы: dict[str, str], тихо: bool = False):
    строк = []
    провалено_блок = 0
    пройдено = 0
    for к in кейсы:
        ок, почему = проверить_кейс(к, ответы.get(к["id"]))
        пройдено += int(ок)
        if not ок and к["блокирующий"]:
            провалено_блок += 1
        метка = "PASS" if ок else ("FAIL" if к["блокирующий"] else "WARN")
        строк.append((метка, к["id"], к["имя"], почему))
    лишние = sorted(set(ответы) - {к["id"] for к in кейсы})
    if not тихо:
        for метка, ид, имя, почему in строк:
            print(f"  [{метка}] {ид:<8} {имя}")
            for п in почему:
                print(f"           └─ не выполнено: {п}")
        if лишние:
            print("\n  ответы на кейсы, которых нет в наборе: "
                  + ", ".join(лишние)
                  + "\n  — набор и прогон разошлись: либо кейс убрали, а прогон "
                    "остался, либо прогон делался по другой версии набора")
    return пройдено, провалено_блок, строк


# ─────────────────────────── самопроверка ───────────────────────────
#
# Правило скилла: измеритель сначала проверяется на заведомо правильном
# примере. Измеритель, который никогда не видел зелёного, обычно зелёного и не
# показывает — и это обнаруживается на клиентском комплекте.

НАБОР_ФИКСТУРЫ = """# Приёмочные кейсы — демо

### Б-9.1 · Навык назван русским именем

**Подать:** «какие навыки ты активировал».

**Признаки:**
- есть: Мониторинг тендеров
- нет: 8_tender-monitor

### Б-9.2 · Ответ начинается картой выдачи

**Подать:** «разбери страницу».

**Признаки:**
- первая-строка-содержит: контур источников
- строк-таблицы>=: 3
- нет: ТЗ на доработку

### О-9.3 · Приёмы лидеров приведены дословно

**Признаки:**
- ссылок>=: 2
- цитат>=: 1
"""

ПРОГОН_ЗЕЛЁНЫЙ = """# Прогон — демо

### Б-9.1

Активировал навык «Мониторинг тендеров» и навык пространства «Работа с
данными Seldon».

### Б-9.2

Контур источников: отраслевые издания, реестры закупок, проектные институты.

| позиция | домен | чей |
|---|---|---|
| 1 | example.ru | конкурент |
| 2 | media.ru | СМИ |
| 3 | tehnoros.ru | мы |

Дальше — расклад по таблице.

### О-9.3

Приём лидера: перечень заголовков с https://example.ru/kran — «Сроки
изготовления и гарантия», далее состав таблицы.
Второй адрес: https://itecokran.ru/liteynye
"""


def самопроверка() -> int:
    кейсы = кейсы_из(НАБОР_ФИКСТУРЫ)
    провалов = 0

    def проба(имя: str, условие: bool, почему: str) -> None:
        nonlocal провалов
        print(("  [v] " if условие else "  [x] ") + имя)
        if not условие:
            провалов += 1
            print("        └─ " + почему)

    проба("набор разобран: три кейса, два блокирующих",
          len(кейсы) == 3 and sum(к["блокирующий"] for к in кейсы) == 2,
          "разбор заголовков сломан — дальше вердикт бессмыслен")

    _, блок, _ = прогнать(кейсы, ответы_из(ПРОГОН_ЗЕЛЁНЫЙ), тихо=True)
    проба("заведомо правильный прогон зелёный", блок == 0,
          "измеритель, не показывающий зелёного, выключают целиком")

    порчи = [
        ("слаг вместо русского имени навыка",
         ПРОГОН_ЗЕЛЁНЫЙ.replace("«Мониторинг тендеров»", "8_tender-monitor")),
        ("ответ начинается не с контура",
         ПРОГОН_ЗЕЛЁНЫЙ.replace("Контур источников: отраслевые издания, "
                                "реестры закупок, проектные институты.",
                                "Сводка по странице.")),
        ("таблица свёрнута до одной строки",
         ПРОГОН_ЗЕЛЁНЫЙ.replace("| 2 | media.ru | СМИ |\n| 3 | tehnoros.ru | мы |\n", "")),
        ("в разборе появилось ТЗ на доработку",
         ПРОГОН_ЗЕЛЁНЫЙ.replace("Дальше — расклад по таблице.",
                                "ТЗ на доработку: раздел 1, раздел 2.")),
        ("на блокирующий кейс нет ответа",
         ПРОГОН_ЗЕЛЁНЫЙ.split("### Б-9.2")[0]),
    ]
    for имя, текст in порчи:
        _, блок, _ = прогнать(кейсы, ответы_из(текст), тихо=True)
        проба(f"ловится: {имя}", блок > 0,
              "признак не сработал — кейс проходит на сломанном ответе")

    # Ложное срабатывание: разметка и форма кавычек не должны менять вердикт.
    метаморф = (ПРОГОН_ЗЕЛЁНЫЙ
                .replace("«Мониторинг тендеров»", "**\"Мониторинг тендеров\"**")
                .replace("Контур источников:", "**Контур источников:**"))
    _, блок, _ = прогнать(кейсы, ответы_из(метаморф), тихо=True)
    проба("разметка и форма кавычек не меняют вердикт", блок == 0,
          "проверка на оформление вместо поведения — тот же дефект, что "
          "«жирное имя навыка» в сверке комплекта")

    кейс_без = кейсы_из("### Б-9.9 · Кейс без признаков\n\n**Подать:** что-нибудь.\n")
    ок, _ = проверить_кейс(кейс_без[0], "любой ответ")
    проба("кейс без машинных признаков не считается пройденным", not ок,
          "кейс, описанный прозой, молча не проверяется ничем и выглядит "
          "в отчёте зелёным")

    print(f"\nсамопроверка: {'все зелёные' if not провалов else str(провалов) + ' провалов'}")
    return 1 if провалов else 0


# ─────────────────────────── точка входа ───────────────────────────

def main() -> int:
    ap = argparse.ArgumentParser(add_help=True)
    ap.add_argument("--кейсы", dest="cases")
    ap.add_argument("--прогон", dest="run")
    ap.add_argument("--самопроверка", dest="self", action="store_true")
    ap.add_argument("--бланк", dest="blank", action="store_true",
                    help="напечатать пустой файл прогона по набору кейсов")
    a = ap.parse_args()

    if a.self:
        print("САМОПРОВЕРКА ИЗМЕРИТЕЛЯ ПРОГОНА")
        return самопроверка()

    if a.blank:
        if not a.cases:
            print("нужен --кейсы")
            return 2
        пк = Path(a.cases)
        if not пк.exists():
            print(f"нет файла: {пк}")
            return 2
        кейсы = кейсы_из(пк.read_text(encoding="utf-8"))
        print(f"# Прогон по набору {пк.name} — <ГГГГ-ММ-ДД>\n")
        print("**Условия:** версия агента V… · пространство … · аккаунт … · "
              "модель … · коннекторы …\n")
        print("> Ответ вставляется целиком, без пересказа: пересказ уже "
              "содержит вывод\n> проверяющего, и проверить его нечем.\n")
        for к in кейсы:
            print(f"### {к['id']}\n\n<{к['имя'].split('·', 1)[-1].strip()}>\n")
        return 0

    if not a.cases or not a.run:
        print("нужны --кейсы и --прогон (или --самопроверка, или --бланк)")
        return 2

    пк, пр = Path(a.cases), Path(a.run)
    if not пк.exists() or not пр.exists():
        print(f"нет файла: {пк if not пк.exists() else пр}")
        print("Если в пути кириллица — проверьте форму Unicode: macOS хранит "
              "имена в NFD, вставленный путь обычно в NFC.")
        return 2

    кейсы = кейсы_из(пк.read_text(encoding="utf-8"))
    ответы = ответы_из(пр.read_text(encoding="utf-8"))
    if not кейсы:
        print(f"в наборе не найдено ни одного кейса: {пк.name}")
        return 2

    print(f"\nПРИЁМОЧНЫЙ ПРОГОН — {пк.name} × {пр.name}\n")
    пройдено, блок, строк = прогнать(кейсы, ответы)
    блокирующих = sum(1 for к in кейсы if к["блокирующий"])
    print(f"\nитог: {пройдено}/{len(кейсы)} кейсов пройдено · "
          f"блокирующих {блокирующих}, провалено {блок}")
    if блок:
        print("\nВерсия не считается внедрённой: провален блокирующий кейс.")
        print("Блокирующее не усредняется — зелёные наблюдательные кейсы его")
        print("не перевешивают.")
        return 1
    print("\nБлокирующие пройдены. Наблюдательные строки со звёздочкой WARN —")
    print("не отказ, но повод посмотреть глазами.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
