def write_if_absent(path: pathlib.Path, text: str, created: list, skipped: list):
    if path.exists():
        skipped.append(path.name)
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    created.append(str(path))


